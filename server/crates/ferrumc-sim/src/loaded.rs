/// The schema version the simulation stamps on chunks it hands off to be saved.
///
/// Chunks generated by the simulation (and any resident chunk re-saved after a
/// mutation) are written under this version so a storage boundary can detect
/// and refuse incompatible data. It is the simulation's notion of "current";
/// storage preserves it verbatim.
pub const CHUNK_SCHEMA_VERSION: SchemaVersion = SchemaVersion::new(1);

/// The schema version stamped on chunk *overlay* records.
///
/// Distinct from [`CHUNK_SCHEMA_VERSION`] (full-chunk snapshots, v1): an overlay
/// carries only the player-modified sections plus a section mask, capture tick,
/// and the chunk's block entities, a different on-disk shape, so it is versioned
/// separately. The current schema carries the complete block-entity section
/// (sign text + chest contents). The simulation refuses every other overlay
/// schema rather than interpreting pre-alpha data under this layout. The
/// simulation owns this application schema; storage preserves it as opaque
/// payload metadata.
pub const OVERLAY_SCHEMA_VERSION: SchemaVersion = SchemaVersion::new(3);

/// How a chunk entered memory during the load-or-generate flow.
///
/// Returned by [`load_or_generate`] and carried by
/// [`ChunkAcquired::NewlyResident`]. The enum is `#[non_exhaustive]`; prefer the
/// [`is_loaded`](Self::is_loaded) / [`is_generated`](Self::is_generated)
/// predicates over matching it directly.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub enum ChunkProvenance {
    /// The chunk was read back from the [`WorldStore`].
    Loaded,

    /// The store had no chunk at the key, so it was freshly generated.
    Generated,
}

impl ChunkProvenance {
    /// Returns `true` if the chunk was read from storage.
    #[must_use]
    pub fn is_loaded(self) -> bool {
        matches!(self, ChunkProvenance::Loaded)
    }

    /// Returns `true` if the chunk was freshly generated on a storage miss.
    #[must_use]
    pub fn is_generated(self) -> bool {
        matches!(self, ChunkProvenance::Generated)
    }
}

/// The outcome of [`LoadedChunkMap::acquire`].
///
/// The enum is `#[non_exhaustive]`; prefer the predicate methods over matching
/// it directly.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub enum ChunkAcquired {
    /// The chunk was not resident, so the load-or-generate flow brought it in.
    /// Carries how it was obtained.
    NewlyResident(ChunkProvenance),

    /// The chunk was already resident; only the new ticket was recorded.
    AlreadyResident,
}

impl ChunkAcquired {
    /// Returns the provenance if the chunk was newly brought into memory, or
    /// `None` if it was already resident.
    #[must_use]
    pub fn provenance(self) -> Option<ChunkProvenance> {
        match self {
            ChunkAcquired::NewlyResident(p) => Some(p),
            ChunkAcquired::AlreadyResident => None,
        }
    }

    /// Returns `true` if the load-or-generate flow ran for this acquire.
    #[must_use]
    pub fn is_newly_resident(self) -> bool {
        matches!(self, ChunkAcquired::NewlyResident(_))
    }

    /// Returns `true` if the chunk was already resident and only a ticket was
    /// added.
    #[must_use]
    pub fn is_already_resident(self) -> bool {
        matches!(self, ChunkAcquired::AlreadyResident)
    }
}

/// The outcome of [`LoadedChunkMap::release`].
///
/// The enum is `#[non_exhaustive]`; prefer the predicate and accessor methods
/// over matching it directly.
#[derive(Debug)]
#[non_exhaustive]
pub enum TicketRelease {
    /// The ticket was removed but the chunk retains other tickets and stays
    /// resident.
    StillLoaded,

    /// The last ticket was removed and the chunk was unloaded.
    ///
    /// Persistence is **not** surfaced here: a chunk's player edits are captured
    /// into overlay records by the appropriate checked capture API at the tick
    /// boundary (and again, by the caller, immediately before an unload). The
    /// caller retains durable retry ownership of those records; an unloaded
    /// chunk then has nothing left to capture. A generated-only
    /// chunk has no persist-dirty sections and therefore costs no storage on
    /// unload, which is the whole point of the persist-dirty signal.
    Unloaded,

    /// No matching ticket existed at the position; nothing changed.
    NotPresent,
}

impl TicketRelease {
    /// Returns `true` if the chunk is still resident after the release.
    #[must_use]
    pub fn is_still_loaded(&self) -> bool {
        matches!(self, TicketRelease::StillLoaded)
    }

    /// Returns `true` if the release unloaded the chunk.
    #[must_use]
    pub fn is_unloaded(&self) -> bool {
        matches!(self, TicketRelease::Unloaded)
    }

    /// Returns `true` if no matching ticket was present.
    #[must_use]
    pub fn is_not_present(&self) -> bool {
        matches!(self, TicketRelease::NotPresent)
    }
}

/// One resident chunk: its data plus the multiset of tickets keeping it loaded.
#[derive(Debug, Clone)]
struct ResidentChunk {
    chunk: Chunk,
    /// Each distinct ticket maps to the number of holders. Every count is `>= 1`;
    /// an entry dropping to zero is removed, and an empty map means the chunk
    /// should be unloaded.
    tickets: BTreeMap<ChunkTicket, usize>,
}

/// Source-compatible alias for the explicit legacy, metadata-free load path.
///
/// See [`load_or_generate_legacy`]. New metadata consumers must instead use
/// [`load_or_generate_bound`]; this alias cannot infer a missing descriptor.
pub async fn load_or_generate(
    store: &dyn WorldStore,
    generator: &FlatWorldGenerator,
    key: ChunkKey,
) -> SimResult<(Chunk, ChunkProvenance)> {
    load_or_generate_legacy(store, generator, key).await
}

/// Runs the historic flat load-or-generate flow on an explicit legacy backend.
///
/// Metadata-enabled stores are refused even when their descriptor happens to
/// match the generator: this path does not declare an expected baseline. The
/// legacy backend's `Unsupported` metadata contract is checked before world
/// reads; all other metadata errors surface as [`SimError::GenerationStore`].
///
/// This preserves the format-3 application path without enabling arbitrary
/// generation changes over descriptor-free data. No descriptor is initialized.
pub async fn load_or_generate_legacy(
    store: &dyn WorldStore,
    generator: &FlatWorldGenerator,
    key: ChunkKey,
) -> SimResult<(Chunk, ChunkProvenance)> {
    validate_load_position(key.pos())?;
    let binding = legacy_generation_binding(GenerationKey::new(key.world(), key.dimension()));
    binding.validate_generator(generator)?;
    validate_legacy_store(store, binding.key()).await?;
    compose_chunk(store, generator, key, binding).await
}

/// Loads a full base or regenerates the explicitly bound base, then applies edits.
///
/// Scope and complete-column bounds are checked before any store or generator
/// call. The generator and persisted descriptor must equal `binding` before
/// world reads or regeneration. Missing, unsupported, corrupt or mismatched
/// metadata is never a chunk miss and never initializes/falls back to a seed.
/// A generator must honor [`ChunkGenerator`]'s stable-identity/deterministic
/// output contract; the simulation additionally validates its returned column.
///
/// Resolution and overlay schema/entity validation are shared with the legacy
/// path. The descriptor is not a Paper terrain parity assertion.
pub async fn load_or_generate_bound(
    store: &dyn WorldStore,
    generator: &dyn ChunkGenerator,
    binding: GenerationBinding,
    key: ChunkKey,
) -> SimResult<(Chunk, ChunkProvenance)> {
    binding.validate_key(key)?;
    validate_load_position(key.pos())?;
    binding.validate_generator(generator)?;
    binding.validate_store(store).await?;
    compose_chunk(store, generator, key, binding).await
}

/// Explicit historical mode: this is not inferred from existing format-3 data.
fn legacy_generation_binding(key: GenerationKey) -> GenerationBinding {
    GenerationBinding::new(key, GenerationIdentity::flat_overworld(WorldSeed::new(0)))
}

async fn validate_legacy_store(store: &dyn WorldStore, key: GenerationKey) -> SimResult<()> {
    match store.load_generation_identity(key).await {
        Err(ferrumc_core::ServerError::Unsupported(_)) => Ok(()),
        Ok(_) => Err(SimError::GenerationBindingRequired { key }),
        Err(source) => Err(SimError::GenerationStore { key, source }),
    }
}

/// Shared composition after the caller has checked bounds and store admission.
///
/// Resolution order, all surfacing a storage failure as [`SimError::ChunkLoad`]:
/// 1. **Base**: use the complete record from [`WorldStore::load_chunk`] when one
///    exists; otherwise generate a fresh flat chunk for `key`'s position.
/// 2. **Overlay**: when [`WorldStore::load_chunk_overlay`] returns a record, apply
///    only its player-modified sections over that base with
///    [`ChunkOverlayRecord::try_apply_to_chunk`]. An imported full record therefore
///    remains authoritative everywhere the overlay has no data.
///
/// An overlay whose schema differs from [`OVERLAY_SCHEMA_VERSION`] is refused
/// with [`StorageError::IncompatiblePreAlphaData`] before any of its data is
/// applied.
/// A malformed or unrepresentable block entity rejects the complete load;
/// invalid contents are never admitted as an empty/default container.
///
/// The returned [`ChunkProvenance`] is [`Loaded`](ChunkProvenance::Loaded) when
/// either record exists and [`Generated`](ChunkProvenance::Generated) only when
/// both reads miss. A loaded chunk is returned clean: both the network and
/// per-flush persist-dirty masks are cleared, since the composition is already
/// persisted. When an overlay exists, the chunk's *cumulative* persist-edited set
/// is additionally reseeded from its sections, so a later edit to a different
/// section re-captures the whole overlay rather than overwriting earlier edits;
/// the per-flush gate stays clear, so the reseed does not itself trigger a flush.
async fn compose_chunk(
    store: &dyn WorldStore,
    generator: &dyn ChunkGenerator,
    key: ChunkKey,
    binding: GenerationBinding,
) -> SimResult<(Chunk, ChunkProvenance)> {
    let pos = key.pos();
    // Store admission may have awaited; reject a changed generator before the
    // first world read, including callers of the free load functions.
    binding.validate_generator(generator)?;

    // The durable full record is the base when present. In particular, this is
    // the shape produced by Anvil import and must not be bypassed merely because
    // the chunk also has a later gameplay overlay.
    let stored = store
        .load_chunk(key)
        .await
        .map_err(|source| SimError::ChunkLoad { pos, source })?;
    let has_stored_base = stored.is_some();
    if let Some(record) = &stored {
        validate_loaded_column(pos, record.chunk().pos())?;
    }
    binding.validate_generator(generator)?;
    let mut chunk = if let Some(record) = stored {
        record.into_chunk()
    } else {
        let generated = generator.generate_chunk(pos);
        validate_loaded_column(pos, generated.pos())?;
        generated
    };
    binding.validate_generator(generator)?;

    // Apply only the overlay's carried sections and block entities over the
    // selected base. An empty overlay is therefore a no-op, not a reason to
    // replace an imported base with generated terrain.
    let overlay = store
        .load_chunk_overlay(key)
        .await
        .map_err(|source| SimError::ChunkLoad { pos, source })?;
    binding.validate_generator(generator)?;
    if let Some(overlay) = overlay {
        validate_loaded_column(pos, overlay.pos())?;
        if overlay.schema_version() != OVERLAY_SCHEMA_VERSION {
            return Err(SimError::ChunkLoad {
                pos,
                source: StorageError::IncompatiblePreAlphaData.into(),
            });
        }

        // Every accepted nonempty overlay carries the chunk's complete
        // block-entity map. Clear the imported base map before applying that
        // snapshot so a removed sign/chest cannot resurrect on reload. A truly
        // empty current overlay remains the explicit no-op required by the load
        // contract.
        let replaces_block_entities = has_stored_base && overlay.section_count() != 0;
        if replaces_block_entities {
            let base_block_entities: Vec<_> = chunk
                .block_entities()
                .map(|(block_pos, _entity)| block_pos)
                .collect();
            for block_pos in base_block_entities {
                chunk.remove_block_entity(block_pos);
            }
        }
        overlay
            .try_apply_to_chunk(&mut chunk)
            .map_err(|source| SimError::ChunkLoad {
                pos,
                source: source.into(),
            })?;
        // Reseed the cumulative persist-edited set from the sections the overlay
        // carried, so the chunk's NEXT overlay flush re-captures them in full.
        // Without this, an edit to a *different* section after this reload would
        // overwrite the stored overlay with only that section and silently drop
        // these — the same last-write-wins data loss the cumulative capture
        // prevents, just across a reload boundary.
        // (Block entities are immune for free: they reload into the map and the
        // capture always serializes the whole map.) This seeds only the cumulative
        // capture set, never the per-flush gate, so the reload does not itself flush.
        for index in overlay.section_indices() {
            chunk.restore_persist_edited_section(index);
        }
        chunk.clear_dirty();
        chunk.clear_persist_dirty();
        return Ok((chunk, ChunkProvenance::Loaded));
    }

    if has_stored_base {
        // Durable records loaded through an in-memory implementation may still
        // carry the source chunk's transient dirty bits, so normalize them here
        // rather than relying on a particular backend decoder.
        chunk.clear_dirty();
        chunk.clear_persist_dirty();
        Ok((chunk, ChunkProvenance::Loaded))
    } else {
        Ok((chunk, ChunkProvenance::Generated))
    }
}

/// A trait implementation may return a record for another column. Enforce this
/// at the simulation admission boundary even when backend validation was bypassed.
fn validate_loaded_column(expected: ChunkPos, actual: ChunkPos) -> SimResult<()> {
    if expected != actual {
        return Err(SimError::ChunkLoad {
            pos: expected,
            source: StorageError::ChunkPositionMismatch { expected, actual }.into(),
        });
    }
    Ok(())
}

/// Origin and all 15 remaining block coordinates must fit before the generator
/// can multiply chunk coordinates; invalid keys never reach storage or generation.
fn validate_load_position(pos: ChunkPos) -> SimResult<()> {
    for coordinate in [pos.x(), pos.z()] {
        if coordinate
            .checked_mul(16)
            .and_then(|origin| origin.checked_add(15))
            .is_none()
        {
            return Err(SimError::ChunkLoad {
                pos,
                source: StorageError::ChunkPositionOutsideDomain { pos }.into(),
            });
        }
    }
    Ok(())
}

/// The chunks a shard owns in memory for one world and dimension.
///
/// Construct a metadata map with [`LoadedChunkMap::with_generation`] or an
/// explicit legacy map with [`LoadedChunkMap::new_legacy`], bring chunks in with
/// [`acquire`](Self::acquire), release them with [`release`](Self::release), and
/// capture pending bound overlays with [`Self::try_take_persist_dirty_verified`]. The map owns chunk
/// *data* but never a database handle: every storage call is made through a
/// borrowed [`WorldStore`] passed per acquire.
///
/// # Determinism
///
/// Residency is keyed by [`ChunkPos`] in an ordered [`BTreeMap`], and tickets in
/// an ordered map keyed by [`ChunkTicket`], so iteration order
/// ([`loaded_positions`](Self::loaded_positions), [`take_dirty`](Self::take_dirty))
/// is fully determined by the set of resident chunks — no hashing randomness
/// leaks in. Given the same store contents and the same acquire/release/mutate
/// sequence, the map reaches an identical state and produces identical dirty
/// batches.
#[derive(Debug, Clone)]
pub struct LoadedChunkMap {
    world: WorldId,
    dimension: DimensionId,
    schema_version: SchemaVersion,
    generation: Option<GenerationBinding>,
    resident: BTreeMap<ChunkPos, ResidentChunk>,
    persist_scan_after: Option<ChunkPos>,
}

impl LoadedChunkMap {
    /// Source-compatible alias for [`Self::new_legacy`].
    ///
    /// Does not establish a generation identity. Metadata stores are rejected
    /// by acquire; new metadata consumers must use [`Self::with_generation`].
    #[must_use]
    pub fn new(world: WorldId, dimension: DimensionId) -> Self {
        Self::new_legacy(world, dimension)
    }

    /// Creates an explicit metadata-free map for the historic format-3 path.
    ///
    /// This mode selects only Minecraft 1.21.8 / `FerrumC` flat revision 1 /
    /// Overworld / seed 0. No historical seed is inferred from data; another
    /// declared generator identity requires explicit metadata mode/migration.
    #[must_use]
    pub fn new_legacy(world: WorldId, dimension: DimensionId) -> Self {
        Self::with_legacy_schema_version(world, dimension, CHUNK_SCHEMA_VERSION)
    }

    /// Source-compatible alias for [`Self::with_legacy_schema_version`].
    #[must_use]
    pub fn with_schema_version(
        world: WorldId,
        dimension: DimensionId,
        schema_version: SchemaVersion,
    ) -> Self {
        Self::with_legacy_schema_version(world, dimension, schema_version)
    }

    /// Creates an explicit legacy map with a caller-selected full-record schema.
    #[must_use]
    pub fn with_legacy_schema_version(
        world: WorldId,
        dimension: DimensionId,
        schema_version: SchemaVersion,
    ) -> Self {
        Self {
            world,
            dimension,
            schema_version,
            generation: None,
            resident: BTreeMap::new(),
            persist_scan_after: None,
        }
    }

    /// Creates a map with an explicitly declared scope and generated baseline.
    ///
    /// The declaration is not a store attestation. Acquires and checked captures
    /// verify existing metadata; bootstrap must initialize it explicitly first.
    #[must_use]
    pub fn with_generation(binding: GenerationBinding) -> Self {
        Self::with_generation_and_schema_version(binding, CHUNK_SCHEMA_VERSION)
    }

    /// Creates a bound map with a caller-selected full-record capture schema.
    #[must_use]
    pub fn with_generation_and_schema_version(
        binding: GenerationBinding,
        schema_version: SchemaVersion,
    ) -> Self {
        let mut map = Self::with_legacy_schema_version(
            binding.key().world(),
            binding.key().dimension(),
            schema_version,
        );
        map.generation = Some(binding);
        map
    }

    /// Returns the explicit baseline, or `None` for the legacy metadata-free mode.
    #[must_use]
    pub const fn generation_binding(&self) -> Option<GenerationBinding> {
        self.generation
    }

    /// Returns the world these chunks belong to.
    #[must_use]
    pub const fn world(&self) -> WorldId {
        self.world
    }

    /// Returns the dimension these chunks belong to.
    #[must_use]
    pub const fn dimension(&self) -> DimensionId {
        self.dimension
    }

    /// Returns the schema version chunks are saved under.
    #[must_use]
    pub const fn schema_version(&self) -> SchemaVersion {
        self.schema_version
    }

    /// Returns the number of resident chunks.
    #[must_use]
    pub fn loaded_count(&self) -> usize {
        self.resident.len()
    }

    /// Returns `true` if the chunk at `pos` is resident.
    #[must_use]
    pub fn is_loaded(&self, pos: ChunkPos) -> bool {
        self.resident.contains_key(&pos)
    }

    /// Returns the resident chunk positions in ascending order.
    pub fn loaded_positions(&self) -> impl Iterator<Item = ChunkPos> + '_ {
        self.resident.keys().copied()
    }

    /// Returns a shared reference to the resident chunk at `pos`, or `None` if it
    /// is not loaded.
    #[must_use]
    pub fn get(&self, pos: ChunkPos) -> Option<&Chunk> {
        self.resident.get(&pos).map(|r| &r.chunk)
    }

    /// Returns a mutable reference to the resident chunk at `pos`, or `None` if
    /// it is not loaded.
    ///
    /// Mutating through the returned reference (for example
    /// [`Chunk::set_block`](ferrumc_world::Chunk::set_block)) marks the affected
    /// sections dirty, so the chunk is included in the next
    /// [`take_dirty`](Self::take_dirty).
    #[must_use]
    pub fn get_mut(&mut self, pos: ChunkPos) -> Option<&mut Chunk> {
        self.resident.get_mut(&pos).map(|r| &mut r.chunk)
    }

    /// Returns the total number of tickets currently held on `pos` (counting
    /// duplicate holders), or `0` if the chunk is not resident.
    #[must_use]
    pub fn ticket_count(&self, pos: ChunkPos) -> usize {
        self.resident
            .get(&pos)
            .map_or(0, |r| r.tickets.values().sum())
    }

    /// Returns one canonical complete ticket-state record for a resident chunk.
    ///
    /// The test-only record carries world, dimension, chunk position, and every
    /// distinct `(reason, level, holder count)` entry. Ticket entries inherit
    /// the resident map's deterministic [`ChunkTicket`] ordering. `None` means
    /// `pos` is not resident.
    #[cfg(test)]
    pub(crate) fn canonical_ticket_state_record(&self, pos: ChunkPos) -> Option<Vec<u8>> {
        let resident = self.resident.get(&pos)?;
        let mut record = Vec::new();
        record.extend_from_slice(&self.world.get().to_be_bytes());
        record.extend_from_slice(&self.dimension.get().to_be_bytes());
        record.extend_from_slice(&pos.x().to_be_bytes());
        record.extend_from_slice(&pos.z().to_be_bytes());
        record.extend_from_slice(
            &u64::try_from(resident.tickets.len())
                .expect("test ticket entry count fits u64")
                .to_be_bytes(),
        );
        for (ticket, holders) in &resident.tickets {
            let reason = match ticket.reason() {
                TicketReason::Spawn => 0,
                TicketReason::Player => 1,
                TicketReason::Forced => 2,
            };
            record.push(reason);
            record.extend_from_slice(&ticket.level().get().to_be_bytes());
            record.extend_from_slice(
                &u64::try_from(*holders)
                    .expect("test ticket holder count fits u64")
                    .to_be_bytes(),
            );
        }
        Some(record)
    }

    /// Returns the chunk's *effective* (strongest, i.e. lowest) ticket level, or
    /// `None` if it is not resident.
    #[must_use]
    pub fn effective_level(&self, pos: ChunkPos) -> Option<TicketLevel> {
        self.resident
            .get(&pos)
            .and_then(|r| r.tickets.keys().map(|t| t.level()).min())
    }

    /// Builds the storage key for a chunk position in this map's world and
    /// dimension.
    fn chunk_key(&self, pos: ChunkPos) -> ChunkKey {
        ChunkKey::new(self.world, self.dimension, pos)
    }

    /// Ensures the chunk at `pos` is resident and records `ticket` on it.
    ///
    /// If the chunk is already resident, the ticket is simply added and
    /// [`ChunkAcquired::AlreadyResident`] is returned. Otherwise the
    /// load-or-generate flow (see [`load_or_generate`]) brings it into memory
    /// with `ticket` as its first ticket, and
    /// [`ChunkAcquired::NewlyResident`] reports how it was obtained.
    ///
    /// Bound maps validate the generator and target store before every acquire,
    /// including an already-resident ticket increment. Legacy maps explicitly
    /// reject metadata stores. Any admission failure leaves resident chunks,
    /// tickets, dirty masks and the persistence cursor unchanged.
    pub async fn acquire(
        &mut self,
        store: &dyn WorldStore,
        generator: &dyn ChunkGenerator,
        pos: ChunkPos,
        ticket: ChunkTicket,
    ) -> SimResult<ChunkAcquired> {
        validate_load_position(pos)?;
        let binding = self.generation.unwrap_or_else(|| {
            legacy_generation_binding(GenerationKey::new(self.world, self.dimension))
        });
        binding.validate_generator(generator)?;
        if self.generation.is_some() {
            binding.validate_store(store).await?;
        } else {
            validate_legacy_store(store, GenerationKey::new(self.world, self.dimension)).await?;
        }
        binding.validate_generator(generator)?;
        if let Some(resident) = self.resident.get_mut(&pos) {
            *resident.tickets.entry(ticket).or_insert(0) += 1;
            return Ok(ChunkAcquired::AlreadyResident);
        }

        // Not resident: run the flow before mutating the map so a load failure
        // leaves residency untouched.
        let key = self.chunk_key(pos);
        let (chunk, provenance) = compose_chunk(store, generator, key, binding).await?;
        let mut tickets = BTreeMap::new();
        tickets.insert(ticket, 1usize);
        self.resident.insert(pos, ResidentChunk { chunk, tickets });
        Ok(ChunkAcquired::NewlyResident(provenance))
    }

    /// Acquires every chunk in `spawn` with its spawn ticket, returning the
    /// number that were newly brought into memory.
    ///
    /// Chunks already resident (for any reason) still receive a spawn ticket but
    /// are not counted as newly resident. Any generation admission or chunk
    /// load failure stops the loop; chunks successfully acquired so far remain
    /// resident. Each acquire independently checks the same explicit binding.
    pub async fn acquire_spawn(
        &mut self,
        store: &dyn WorldStore,
        generator: &dyn ChunkGenerator,
        spawn: &SpawnChunkTickets,
    ) -> SimResult<usize> {
        let ticket = spawn.ticket();
        let mut newly_resident = 0;
        for pos in spawn.positions() {
            if self
                .acquire(store, generator, pos, ticket)
                .await?
                .is_newly_resident()
            {
                newly_resident += 1;
            }
        }
        Ok(newly_resident)
    }

    /// Releases one `ticket` from the chunk at `pos`.
    ///
    /// Decrements that ticket's holder count. If it was the chunk's last ticket
    /// the chunk is unloaded ([`TicketRelease::Unloaded`]). Persistence is not
    /// surfaced here: the caller must successfully capture pending gameplay
    /// edits via the appropriate checked capture API before releasing the last
    /// ticket and retain the returned records until durable success. A
    /// generated-only chunk costs no storage. Releasing a ticket that is not held (or a chunk that is not
    /// resident) is a no-op reported as [`TicketRelease::NotPresent`].
    pub fn release(&mut self, pos: ChunkPos, ticket: ChunkTicket) -> TicketRelease {
        let Some(resident) = self.resident.get_mut(&pos) else {
            return TicketRelease::NotPresent;
        };
        let Entry::Occupied(mut entry) = resident.tickets.entry(ticket) else {
            return TicketRelease::NotPresent;
        };
        let count = entry.get_mut();
        *count -= 1;
        if *count == 0 {
            entry.remove();
        }
        if !resident.tickets.is_empty() {
            return TicketRelease::StillLoaded;
        }

        // Last ticket gone: unload and drop the chunk.
        match self.resident.remove(&pos) {
            Some(_) => TicketRelease::Unloaded,
            // `pos` was present at the start of the method and only this `&mut`
            // path could have removed it, so this arm is unreachable; report it
            // as a no-op rather than panicking.
            None => TicketRelease::NotPresent,
        }
    }

    /// Collects every resident chunk with unsaved changes as a save batch and
    /// marks those chunks clean.
    ///
    /// Each returned `(ChunkKey, ChunkRecord)` is a snapshot ready to hand to
    /// [`WorldStore::save_chunks`]. The chunks' dirty flags are cleared here on
    /// the assumption the batch will be persisted; this method does not perform
    /// the save and intentionally implements no flush *policy* (when to call it,
    /// and what to do if the save later fails, are the caller's concern). The
    /// batch is ordered by [`ChunkPos`] for determinism. This legacy drain is a
    /// no-op on bound maps: it cannot validate a target store and must not clear
    /// dirty ownership or expose unchecked save records. It is not a metadata
    /// flush-success signal; use the checked bound overlay capture instead.
    #[must_use]
    pub fn take_dirty(&mut self) -> Vec<(ChunkKey, ChunkRecord)> {
        if self.generation.is_some() {
            return Vec::new();
        }
        let world = self.world;
        let dimension = self.dimension;
        let schema = self.schema_version;
        let mut batch = Vec::new();
        for (&pos, resident) in &mut self.resident {
            if resident.chunk.dirty_sections().any() {
                resident.chunk.clear_dirty();
                batch.push((
                    ChunkKey::new(world, dimension, pos),
                    ChunkRecord::new(schema, resident.chunk.clone()),
                ));
            }
        }
        batch
    }

    /// Returns `true` if any resident chunk has unsaved gameplay edits.
    ///
    /// A cheap pre-check for the flush hot path: the driver only reserves a
    /// storage-channel slot when there is something to persist.
    #[must_use]
    pub fn has_persist_dirty(&self) -> bool {
        self.resident
            .values()
            .any(|resident| resident.chunk.persist_dirty_sections().any())
    }

    /// Collects an overlay record for every resident chunk with unsaved gameplay
    /// edits and clears those chunks' persist-dirty masks.
    ///
    /// This is the persistence handoff: unlike [`take_dirty`](Self::take_dirty)
    /// (which emits a full [`ChunkRecord`] for any network-dirty chunk, including
    /// a freshly generated one), this emits a [`ChunkOverlayRecord`] carrying every
    /// section a gameplay edit has ever touched (the chunk's cumulative persist-edited
    /// set), gated on the per-flush persist-dirty signal. Capturing the cumulative set
    /// on each flush keeps the store's last-write-wins overwrite a complete snapshot,
    /// so edits to different sections on different flush ticks are not lost on reload.
    /// A generated-but-never-edited chunk has an empty persist-dirty mask and so is
    /// **never** included, which is what keeps untouched terrain at zero storage.
    /// Each overlay is stamped with `tick` as its capture time and
    /// [`OVERLAY_SCHEMA_VERSION`]. The batch is ordered by [`ChunkPos`] for
    /// determinism. As with `take_dirty`, this captures and clears but does not
    /// itself persist — flush *policy* is the caller's. This legacy public path
    /// retains its complete-drain behavior and lossy entity capture for source
    /// compatibility. Production consumers must instead use
    /// [`Self::try_take_persist_dirty_bounded`]; the experimental scheduler still
    /// uses the separately bounded legacy variant.
    /// On bound maps it is a no-op, preserving all masks and the cursor; an
    /// empty result must never be used as a metadata flush-success signal.
    #[must_use]
    pub fn take_persist_dirty(&mut self, tick: u64) -> Vec<(ChunkKey, ChunkOverlayRecord)> {
        if self.generation.is_some() {
            return Vec::new();
        }
        let batch = self.take_persist_dirty_up_to(tick, usize::MAX);
        self.persist_scan_after = None;
        batch
    }

    /// Captures a bounded, lossless batch and then transfers its dirty ownership.
    ///
    /// The requested `capacity` is clamped to [`MAX_SAVE_BATCH`] before allocation.
    /// Every selected overlay is captured immutably first. Only after the entire
    /// batch succeeds are its per-flush masks cleared and its deterministic scan
    /// continuation advanced. A failure leaves all chunks and that continuation
    /// unchanged, including records captured before the failing one.
    ///
    /// The continuation visits deferred higher keys before wrapping, so repeatedly
    /// re-dirtying lower keys cannot starve the tail. The returned batch is sorted
    /// by chunk position even when selection wraps. Cumulative edited masks remain
    /// set so each record is a complete overlay snapshot. This transfers ownership
    /// into the returned records; the caller still owns durable save and retry.
    ///
    /// # Errors
    ///
    /// Returns the checked storage capture error for an invalid/unrepresentable
    /// entity or record. No selected dirty mask is cleared on any such error.
    /// This synchronous source-compatible API is legacy-only and returns
    /// [`StorageError::GenerationMetadataUnsupported`] on a bound map because
    /// it has no target-store authorization. Bound consumers use
    /// [`Self::try_take_persist_dirty_verified`] or
    /// [`Self::try_take_persist_dirty_bound`].
    pub fn try_take_persist_dirty_bounded(
        &mut self,
        tick: u64,
        capacity: NonZeroUsize,
    ) -> Result<Vec<(ChunkKey, ChunkOverlayRecord)>, StorageError> {
        if self.generation.is_some() {
            return Err(StorageError::GenerationMetadataUnsupported);
        }
        self.capture_persist_dirty_checked(tick, capacity)
    }

    /// Checks the target store afresh, then captures a complete bounded batch.
    ///
    /// This async option borrows the store without retaining a handle. Every
    /// metadata check and every selected record's codec preflight succeeds
    /// before any mask clears or the continuation advances. Missing/corrupt/
    /// incompatible metadata and late record failures retain all dirty facts.
    /// Durable save and retry remain the caller's responsibility.
    ///
    /// On the synchronous tick hot path, prefer off-tick verification with
    /// [`GenerationBinding::verify_store`] and [`Self::try_take_persist_dirty_verified`].
    pub async fn try_take_persist_dirty_bound(
        &mut self,
        store: &dyn WorldStore,
        tick: u64,
        capacity: NonZeroUsize,
    ) -> SimResult<Vec<(ChunkKey, ChunkOverlayRecord)>> {
        let binding = self.require_generation_binding()?;
        binding.validate_store(store).await?;
        self.capture_persist_dirty_checked(tick, capacity)
            .map_err(|source| SimError::PersistCapture { source })
    }

    /// Captures against an opaque authorization for the exact immutable store.
    ///
    /// This performs no storage I/O. The token's scope, descriptor and weak
    /// allocation identity must match the map and the supplied target `Arc`
    /// before the whole bounded codec preflight and dirty-ownership transfer.
    /// Clones of the verified `Arc` work; a different same-content store does
    /// not. Any refusal preserves chunks, masks, tickets and continuation.
    ///
    /// App bootstrap verifies off-tick. Driver and writer must share this exact
    /// store allocation. Keep returned batches until durable success; validate
    /// the expected binding before initial writer saves and retries, and never
    /// retarget an already captured batch to another store or baseline.
    pub fn try_take_persist_dirty_verified(
        &mut self,
        store: &Arc<dyn WorldStore>,
        verified: &VerifiedGenerationBinding,
        tick: u64,
        capacity: NonZeroUsize,
    ) -> SimResult<Vec<(ChunkKey, ChunkOverlayRecord)>> {
        verified.validate(self.require_generation_binding()?, store)?;
        self.capture_persist_dirty_checked(tick, capacity)
            .map_err(|source| SimError::PersistCapture { source })
    }

    fn require_generation_binding(&self) -> SimResult<GenerationBinding> {
        self.generation.ok_or(SimError::GenerationBindingRequired {
            key: GenerationKey::new(self.world, self.dimension),
        })
    }

    fn capture_persist_dirty_checked(
        &mut self,
        tick: u64,
        capacity: NonZeroUsize,
    ) -> Result<Vec<(ChunkKey, ChunkOverlayRecord)>, StorageError> {
        let capacity = capacity.get().min(MAX_SAVE_BATCH);
        let mut batch = Vec::with_capacity(capacity.min(self.resident.len()));
        let mut last_selected = None;
        let after = self.persist_scan_after;
        let following = self
            .resident
            .range((after.map_or(Unbounded, Excluded), Unbounded));
        let wrapping = self
            .resident
            .range((Unbounded, after.map_or(Unbounded, Included)))
            .take(if after.is_some() {
                self.resident.len()
            } else {
                0
            });
        for (&pos, resident) in following
            .chain(wrapping)
            .filter(|(_, resident)| resident.chunk.persist_dirty_sections().any())
            .take(capacity)
        {
            let record = ChunkOverlayRecord::try_from_chunk(
                OVERLAY_SCHEMA_VERSION,
                pos,
                &resident.chunk,
                tick,
            )?;
            batch.push((ChunkKey::new(self.world, self.dimension, pos), record));
            last_selected = Some(pos);
        }

        // There are no awaits or external mutation between immutable selection
        // and commit: every selected position still belongs to this map.
        for (key, _) in &batch {
            if let Some(resident) = self.resident.get_mut(&key.pos()) {
                resident.chunk.clear_persist_dirty();
            }
        }
        self.persist_scan_after = if self.has_persist_dirty() {
            last_selected
        } else {
            None
        };
        batch.sort_unstable_by_key(|(key, _)| key.pos());
        Ok(batch)
    }

    /// Collects at most `capacity` persist-dirty overlays in deterministic
    /// chunk order.
    ///
    /// Only records transferred into the returned vector have their per-flush
    /// dirty masks cleared. A deterministic continuation cursor visits the
    /// deferred tail before wrapping to lower keys, so repeatedly re-dirtying a
    /// low chunk cannot starve older work. Returned records remain sorted by
    /// chunk position even when selection wraps.
    /// This experimental scheduler seam retains legacy lossy entity capture;
    /// production persistence must use [`Self::try_take_persist_dirty_bounded`].
    /// Bound maps are not supported by this legacy scheduler seam: the no-op
    /// keeps dirty facts/cursor intact until an authorized consumer captures them.
    pub(crate) fn take_persist_dirty_bounded(
        &mut self,
        tick: u64,
        capacity: NonZeroUsize,
    ) -> Vec<(ChunkKey, ChunkOverlayRecord)> {
        if self.generation.is_some() {
            return Vec::new();
        }
        let capacity = capacity.get();
        let world = self.world;
        let dimension = self.dimension;
        let mut batch = Vec::with_capacity(capacity.min(self.resident.len()));
        let mut last_selected = None;

        if let Some(after) = self.persist_scan_after {
            for (&pos, resident) in self.resident.range_mut((Excluded(after), Unbounded)) {
                if batch.len() >= capacity {
                    break;
                }
                if let Some(record) =
                    Self::take_persist_record(world, dimension, tick, pos, resident)
                {
                    batch.push(record);
                    last_selected = Some(pos);
                }
            }
            if batch.len() < capacity {
                for (&pos, resident) in self.resident.range_mut(..=after) {
                    if batch.len() >= capacity {
                        break;
                    }
                    if let Some(record) =
                        Self::take_persist_record(world, dimension, tick, pos, resident)
                    {
                        batch.push(record);
                        last_selected = Some(pos);
                    }
                }
            }
        } else {
            for (&pos, resident) in &mut self.resident {
                if batch.len() >= capacity {
                    break;
                }
                if let Some(record) =
                    Self::take_persist_record(world, dimension, tick, pos, resident)
                {
                    batch.push(record);
                    last_selected = Some(pos);
                }
            }
        }

        self.persist_scan_after = if self.has_persist_dirty() {
            last_selected
        } else {
            None
        };
        batch.sort_unstable_by_key(|(key, _)| key.pos());
        batch
    }

    /// Shared deterministic persist capture with an explicit record ceiling.
    fn take_persist_dirty_up_to(
        &mut self,
        tick: u64,
        capacity: usize,
    ) -> Vec<(ChunkKey, ChunkOverlayRecord)> {
        let world = self.world;
        let dimension = self.dimension;
        let mut batch = Vec::with_capacity(capacity.min(self.resident.len()));
        for (&pos, resident) in &mut self.resident {
            if batch.len() >= capacity {
                break;
            }
            if let Some(record) = Self::take_persist_record(world, dimension, tick, pos, resident) {
                batch.push(record);
            }
        }
        batch
    }

    /// Captures one dirty resident and clears only the transferred flush mask.
    fn take_persist_record(
        world: WorldId,
        dimension: DimensionId,
        tick: u64,
        pos: ChunkPos,
        resident: &mut ResidentChunk,
    ) -> Option<(ChunkKey, ChunkOverlayRecord)> {
        if !resident.chunk.persist_dirty_sections().any() {
            return None;
        }
        let record =
            ChunkOverlayRecord::from_chunk(OVERLAY_SCHEMA_VERSION, pos, &resident.chunk, tick);
        resident.chunk.clear_persist_dirty();
        Some((ChunkKey::new(world, dimension, pos), record))
    }
}

