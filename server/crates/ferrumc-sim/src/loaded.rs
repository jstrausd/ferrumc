//! The set of chunks a shard owns in memory, governed by tickets.
//!
//! A [`LoadedChunkMap`] is the shard's exclusive owner of chunk data for one
//! world and dimension. A chunk becomes resident the moment it gets its first
//! [`ChunkTicket`] (via [`LoadedChunkMap::acquire`], which runs the
//! load-or-generate flow) and is unloaded the moment its last ticket is released
//! (via [`LoadedChunkMap::release`]). The map therefore maintains one
//! invariant at all times:
//!
//! > A chunk position is resident **iff** it holds at least one ticket.
//!
//! Mutations to a resident chunk mark it dirty (the chunk tracks this itself).
//! There are two handoffs: [`LoadedChunkMap::take_dirty`] emits a full
//! [`ChunkRecord`] for every network-dirty chunk (including freshly generated
//! ones), while [`LoadedChunkMap::take_persist_dirty`] emits a
//! [`ChunkOverlayRecord`] only for chunks a *gameplay* edit marked persist-dirty
//! — so untouched generated terrain produces zero overlay records. This module
//! collects but never persists; choosing *when* to flush is the caller's policy,
//! deliberately out of scope here. The crate-internal multi-shard scheduler uses
//! a bounded canonical-order variant with a deterministic continuation cursor,
//! leaving overflow dirty without allowing low-key re-dirties to starve it.
//! Bound maps use the checked authorized capture APIs; the legacy drains cannot
//! clear their dirty ownership without target-store validation.

