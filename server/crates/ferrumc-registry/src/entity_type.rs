//! Validated, allocation-free entity-type lookups for Minecraft 1.21.8.
//!
//! The original static registry is generated at build time from the unchanged
//! CAT-02.1 fixture. This module supplies type identity, not entity behavior,
//! metadata, spawning eligibility, dimensions, tracking or AI. Unknown inputs
//! are refused instead of falling back to the original registry's default pig.

use std::iter::FusedIterator;

include!(concat!(env!("OUT_DIR"), "/entity_types_generated.rs"));

/// One registered entity *type* from the pinned Minecraft 1.21.8 registry.
///
/// This identifies a type, such as `minecraft:item`, rather than an entity
/// instance's UUID, wire entity id, or local storage handle. Construction checks
/// the registry. It has no unchecked constructor, default, or deserialization.
///
/// ```compile_fail
/// use ferrumc_registry::entity_type::EntityTypeId;
/// let fabricated = EntityTypeId(999);
/// ```
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct EntityTypeId(i32);

impl EntityTypeId {
    /// Checks a raw entity-type protocol id against this exact version's registry.
    ///
    /// Negative and unknown values return `None`; there is no default fallback.
    /// This lookup performs no allocation.
    pub fn try_from_protocol_id(id: i32) -> Option<Self> {
        let index = usize::try_from(id).ok()?;
        ENTITY_TYPE_NAMES.get(index).map(|_| Self(id))
    }

    /// Resolves a canonical `minecraft:` name or exact bare name without allocation.
    ///
    /// Names are case-sensitive. Other namespaces, malformed and unknown names
    /// return `None`; no whitespace, case or resource-path normalization occurs.
    pub fn from_name(name: &str) -> Option<Self> {
        lookup_entity_type(name)
    }

    /// Returns the entity-type protocol id for Minecraft 1.21.8.
    pub const fn protocol_id(self) -> i32 {
        self.0
    }

    /// Returns this registered type's canonical namespaced resource location.
    ///
    /// All constructors preserve the valid direct-index invariant.
    pub fn resource_location(self) -> &'static str {
        ENTITY_TYPE_NAMES[self.0 as usize]
    }

    /// Returns whether this is the original `minecraft:player` type.
    ///
    /// This is identity classification only; it does not create player state or
    /// grant admission into a non-player entity store. The id is generated by
    /// name from the source fixture, never copied from a separate list.
    pub const fn is_player(self) -> bool {
        self.0 == PLAYER_PROTOCOL_ID
    }
}

/// Resolves an exact canonical or bare entity-type name without allocation.
///
/// ```
/// use ferrumc_registry::entity_type::lookup_entity_type;
/// let item = lookup_entity_type("minecraft:item").unwrap();
/// assert_eq!(item.protocol_id(), 69);
/// assert_eq!(item.resource_location(), "minecraft:item");
/// assert!(!item.is_player());
/// assert!(lookup_entity_type("other:item").is_none());
/// ```
pub fn lookup_entity_type(name: &str) -> Option<EntityTypeId> {
    let bare = name.strip_prefix("minecraft:").unwrap_or(name);
    let index = ENTITY_TYPES_BY_NAME
        .binary_search_by(|&(candidate, _)| candidate.cmp(bare))
        .ok()?;
    Some(EntityTypeId(ENTITY_TYPES_BY_NAME[index].1))
}

/// Resolves a raw protocol type id to its canonical name without allocation.
///
/// Negative or unknown ids return `None`, including the first value beyond the
/// registry. This does not use the original defaulted-registry fallback.
pub fn lookup_entity_type_name(id: i32) -> Option<&'static str> {
    EntityTypeId::try_from_protocol_id(id).map(EntityTypeId::resource_location)
}

/// Iterates all registered entity types in ascending protocol-id order.
///
/// The iterator borrows static data through valid ids; it allocates no result
/// collection and supports `.take(budget)` and `.skip(offset)` pagination.
pub fn entity_types(
) -> impl ExactSizeIterator<Item = EntityTypeId> + DoubleEndedIterator + FusedIterator {
    (0..ENTITY_TYPE_COUNT_I32).map(EntityTypeId)
}
