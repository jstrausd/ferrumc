#!/usr/bin/env python3
"""Generate closed 1.21.8 smelting/fuel facts from the pinned complete resources.

Usage: generate_smelting.py /path/to/paper-1.21.8-reference
The receipt locks all input bytes; the first generation creates that receipt.
Every generation verifies an immutable digest of the source receipt.
"""
import ast
import hashlib
import json
from pathlib import Path
import re
import struct
import subprocess
import sys

PIN = "29c8822d90899c89d2689338e81a98f690bcba12"
SOURCE_DIGEST = "01d244f7fd9d737cd37f372b229ba1eb004deeb01d36805fd4f0e3bd76b0c6a2"
ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path(sys.argv[1]).resolve()
RESOURCES = SOURCE / "paper-server/src/minecraft/resources/data/minecraft"
INPUTS = {}


def check(condition, message):
    if not condition:
        raise SystemExit(str(message))


def read(path):
    raw = path.read_bytes()
    INPUTS[str(path.relative_to(SOURCE))] = hashlib.sha256(raw).hexdigest()
    return raw.decode()


def tag(name, visiting=()):
    check(name.startswith("minecraft:"), name)
    check(name not in visiting, name)
    data = json.loads(read(RESOURCES / "tags/item" / (name.split(":", 1)[1] + ".json")))
    values = set()
    for value in data["values"]:
        if isinstance(value, dict):
            check(value.get("required", True), value)
            value = value["id"]
        if value.startswith("#"):
            values.update(tag(value[1:], visiting + (name,)))
        else:
            values.add(value)
    return values


def ingredients(value):
    if isinstance(value, list):
        return set().union(*(ingredients(item) for item in value))
    check(isinstance(value, str), value)
    return tag(value[1:]) if value.startswith("#") else {value}


recipes = []
for path in sorted((RESOURCES / "recipe").glob("*.json")):
    # Non-smelting resource files are not admitted or included in the receipt.
    raw = path.read_text()
    recipe = json.loads(raw)
    if recipe.get("type") != "minecraft:smelting":
        continue
    read(path)
    check(set(recipe["result"]) == {"id"}, recipe)
    ticks = recipe.get("cookingtime", 200)
    check(ticks == 200, (path, ticks))
    bits = struct.unpack(">I", struct.pack(">f", recipe.get("experience", 0.0)))[0]
    for item in sorted(ingredients(recipe["ingredient"])):
        recipes.append((item, "minecraft:" + path.stem, recipe["result"]["id"], ticks, bits))
check(len({row[1] for row in recipes}) == 72, "expected 72 smelting recipes")

fuel_source = read(SOURCE / "paper-server/src/minecraft/java/net/minecraft/world/level/block/entity/FuelValues.java")
chain = fuel_source.split("return new FuelValues.Builder(registries, enabledFeatures)", 1)[1].split(".build();", 1)[0]
fuels = {}


def arithmetic(node):
    if isinstance(node, ast.Constant) and type(node.value) is int:
        return node.value
    check(isinstance(node, ast.BinOp), ast.dump(node))
    left, right = arithmetic(node.left), arithmetic(node.right)
    if isinstance(node.op, ast.Add):
        return left + right
    if isinstance(node.op, ast.Mult):
        return left * right
    check(isinstance(node.op, ast.Div), ast.dump(node))
    return left // right


for method, reference, expression in re.findall(r"\.(add|remove)\((ItemTags\.\w+|Items\.\w+|Blocks\.\w+)(?:,\s*([^\)]+))?\)", chain):
    owner, name = reference.split(".")
    names = tag("minecraft:" + name.lower()) if owner == "ItemTags" else {"minecraft:" + name.lower()}
    if method == "remove":
        for name in names:
            fuels.pop(name, None)
    else:
        ticks = arithmetic(ast.parse(expression.replace("smeltingTime", "200"), mode="eval").body)
        check(0 < ticks <= 20000, "invalid fuel duration")
        for name in names:
            fuels[name] = ticks
check(fuels["minecraft:lava_bucket"] == 20000, "lava fuel duration mismatch")
check(fuels["minecraft:coal"] == 1600, "coal fuel duration mismatch")
check("minecraft:crimson_planks" not in fuels, "nonflammable wood survived fuel removal")

receipt = {"paper_commit": PIN, "inputs": dict(sorted(INPUTS.items()))}
digest = hashlib.sha256(json.dumps(receipt, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
check(digest == SOURCE_DIGEST, "pinned source bytes changed")
receipt_path = ROOT / "src/smelting/sources.json"
receipt_path.parent.mkdir(parents=True, exist_ok=True)
if receipt_path.exists():
    check(json.loads(receipt_path.read_text()) == receipt, "pinned source receipt changed")
else:
    receipt_path.write_text(json.dumps(receipt, indent=2) + "\n")

out = ["// Generated by tools/generate_smelting.py; do not edit.",
       "// Paper 1.21.8 build 60; commit " + PIN + ".",
       "pub(super) const RECIPES: &[(&str, &str, &str, u16, u32)] = &["]
for item, name, result, ticks, bits in recipes:
    hex_bits = f"{bits:08x}"
    out.append(f'    ("{item}", "{name}", "{result}", {ticks}, 0x{hex_bits[:4]}_{hex_bits[4:]}),')
out += ["];", "pub(super) const FUELS: &[(&str, u16)] = &["]
for name, ticks in sorted(fuels.items()):
    out.append(f'    ("{name}", {ticks}),')
out.append("];")
(ROOT / "src/smelting/data.rs").write_text("\n".join(out) + "\n")
subprocess.run(["rustfmt", "--edition", "2021", str(ROOT / "src/smelting/data.rs")], check=True)
print(f"72 recipes, {len(recipes)} expanded ingredient rows, {len(fuels)} fuels; {len(INPUTS)} pinned sources")
