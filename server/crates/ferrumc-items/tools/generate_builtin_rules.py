#!/usr/bin/env python3
"""Emit a closed normal item-rule table from the pinned 1.21.8 registry snapshot."""
import hashlib
import json
import struct
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT.parent / 'ferrumc-registry/data/items.json'
SHA256 = 'a790e2ea77f54cb3d1640577f6c86c94f7f66a3168fe38928fc55066162579bb'
raw = SOURCE.read_bytes()
if hashlib.sha256(raw).hexdigest() != SHA256:
    raise SystemExit('pinned items.json hash mismatch')
items = json.loads(raw)
lines = ['// @generated by tools/generate_builtin_rules.py; do not hand-edit.\n',
         '// Pinned Minecraft1.21.8 registry snapshot SHA256 ' + SHA256 + '\n',
         'use super::{ArmorProperties, ArmorSlot, FoodEffect, FoodEffectKind, FoodProperties, ToolProperties};\n']

def float_literal(value):
    bits = struct.unpack('>I', struct.pack('>f', float(value)))[0]
    text = f'{bits:08x}'
    return f'f32::from_bits(0x{text[:4]}_{text[4:]})'

def boolean(value):
    return 'true' if value else 'false'

def effects(consumable):
    results = []
    kinds = {'hunger':'Hunger','poison':'Poison','nausea':'Nausea','regeneration':'Regeneration','resistance':'Resistance','fire_resistance':'FireResistance','absorption':'Absorption'}
    for effect in consumable.get('on_consume_effects', []):
        typ = effect['type']
        if typ == 'minecraft:apply_effects':
            for status in effect['effects']:
                name = status['id'].removeprefix('minecraft:')
                results.append(f'FoodEffect {{ kind: FoodEffectKind::{kinds[name]}, ticks: {status["duration"]}, amplifier: {status.get("amplifier",0)}, probability: {float_literal(effect.get("probability",1.0))} }}')
        elif typ == 'minecraft:remove_effects' and effect['effects'] == 'minecraft:poison':
            results.append('FoodEffect { kind: FoodEffectKind::ClearPoison, ticks: 0, amplifier: 0, probability: 1.0 }')
        elif typ == 'minecraft:teleport_randomly':
            results.append('FoodEffect { kind: FoodEffectKind::RandomTeleport, ticks: 0, amplifier: 0, probability: 1.0 }')
        else:
            raise SystemExit('unknown food consume effect ' + repr(effect))
    return '&[' + ','.join(results) + ']'

foods = []
for name, record in sorted(items.items()):
    c = record['components']
    if 'minecraft:food' not in c:
        continue
    f = c['minecraft:food']; consumable = c['minecraft:consumable']
    remainder = c.get('minecraft:use_remainder', {}).get('id')
    if remainder:
        remainder = 'Some("' + remainder + '")'
    else:
        remainder = 'None'
    ticks = int(float(consumable.get('consume_seconds', 1.6)) * 20)
    foods.append(f'("minecraft:{name}", FoodProperties {{ nutrition: {f["nutrition"]}, saturation: {float_literal(f["saturation"])}, always_edible: {boolean(f.get("can_always_eat",False))}, consume_ticks: {ticks}, remainder_name: {remainder}, effects: {effects(consumable)} }}),\n')
if len(foods) != 40:
    raise SystemExit('expected all40 original food items')
lines += ['pub(super) const FOODS: &[(&str, FoodProperties)] = &[\n', *foods, '];\n']

lines.append('pub(super) const DURABILITY: &[(&str, i32)] = &[\n')
for name, record in sorted(items.items()):
    damage = record['components'].get('minecraft:max_damage')
    if damage is not None:
        if record['components'].get('minecraft:damage') != 0:
            raise SystemExit('unexpected original damage default')
        lines.append(f'("minecraft:{name}", {damage}),\n')
lines.append('];\n')

slots = {'head':'Helmet', 'chest':'Chestplate', 'legs':'Leggings', 'feet':'Boots'}
lines.append('pub(super) const ARMOR: &[(&str, ArmorProperties)] = &[\n')
for name, record in sorted(items.items()):
    c = record['components']; eq = c.get('minecraft:equippable', {})
    if eq.get('slot') not in slots:
        continue
    attrs = {a['type']:a['amount'] for a in c['minecraft:attribute_modifiers'] if a['operation'] == 'add_value'}
    lines.append(f'("minecraft:{name}", ArmorProperties {{ slot: ArmorSlot::{slots[eq["slot"]]}, armor: {float_literal(attrs.get("minecraft:armor",0.0))}, toughness: {float_literal(attrs.get("minecraft:armor_toughness",0.0))}, knockback_resistance: {float_literal(attrs.get("minecraft:knockback_resistance",0.0))}, damage_on_hurt: {boolean(eq.get("damage_on_hurt",True))}, swappable: {boolean(eq.get("swappable",True))} }}),\n')
lines.append('];\n')

lines.append('pub(super) const TOOLS: &[(&str, ToolProperties)] = &[\n')
for name, record in sorted(items.items()):
    c = record['components']
    if 'minecraft:tool' not in c and 'minecraft:weapon' not in c:
        continue
    attrs = {a['type']:a['amount'] for a in c['minecraft:attribute_modifiers'] if a['operation'] == 'add_value' and a.get('slot') == 'mainhand'}
    tool = c.get('minecraft:tool', {})
    block_damage = tool.get('damage_per_block', 1) if 'minecraft:tool' in c else 0
    attack_damage = c.get('minecraft:weapon', {}).get('item_damage_per_attack', 1) if 'minecraft:weapon' in c else 0
    lines.append(f'("minecraft:{name}", ToolProperties {{ attack_damage: {float_literal(1.0 + attrs.get("minecraft:attack_damage",0.0))}, attack_speed: {float_literal(4.0 + attrs.get("minecraft:attack_speed",0.0))}, block_durability_cost: {block_damage}, attack_durability_cost: {attack_damage} }}),\n')
lines.append('];\n')
(ROOT / 'src/rules/data.rs').write_text(''.join(lines))
subprocess.run(['rustfmt', '--edition', '2021', str(ROOT / 'src/rules/data.rs')], check=True)
print('Generated40food,68durability and exactequipment/tool defaults from pinnedregistry.')
