#!/usr/bin/env python3
"""Produce normal crafting descriptors/cases by calling the actual original JAR.

Usage: generate_normal_crafting.py ORIGINAL_CACHE JAVA_HOME OUTPUT_DIR
Copies no matching, tag-expansion, output assembly or remainder formulas.
"""
import collections
import hashlib
import json
import os
from pathlib import Path
import platform
import re
import subprocess
import sys
import tempfile
import zipfile

PINS = {
    "bundle": "2349d9a8f0d4be2c40e7692890ef46a4b07015e7955b075460d02793be7fbbe7",
    "inner": "2bee159e4ce87ae857b4323f9f32c7a3d7d448f7f8c3f62fa6f295a72e228250",
    "mappings": "e373ba569839e6f3c7bd4880247f3e85577d92cde2c605adfa2024eb9cae503e",
    "recipes": "023cc012b9e01b138831c302bdfb956e4179203b447a9e1826fc0939f285a232",
}
HELPER = "ferrumc/reference/NormalCraftingOracle.class"
MAX_EXPORT = 64 * 1024 * 1024


def require(condition, message):
    if not condition:
        raise ValueError(message)


def sha256(path):
    with path.open("rb") as source:
        return hashlib.file_digest(source, "sha256").hexdigest()


def verify(path, expected, label):
    require(path.is_file() and not path.is_symlink(), f"invalid {label} file")
    require(sha256(path) == expected, f"{label} SHA256 mismatch")


def reject_shadow(classpath):
    for path in classpath:
        with zipfile.ZipFile(path) as archive:
            require(HELPER not in archive.namelist(), f"helper classpath shadow: {path.name}")


def rust_string(value):
    require(re.fullmatch(r"minecraft:[a-z0-9_./]+", value) is not None, "noncanonical resource")
    return json.dumps(value)


def producer(records, fixture):
    items = sorted((r for r in records if r["kind"] == "item"), key=lambda r: r["source"])
    recipes = [r for r in records if r["kind"] == "recipe"]
    cases = [r for r in records if r["kind"] == "case"]
    require(len(recipes) == 968 and sum(r["shaped"] for r in recipes) == 673, "recipe census mismatch")
    require(len({r["name"] for r in recipes}) == 968, "duplicate recipe identity")
    require(len(items) == len({r["source"] for r in items}) == len({r["id"] for r in items}), "duplicate original item")
    item_ids = {r["source"]: r["id"] for r in items}
    sets = sorted({tuple(sorted(item_ids[name] for name in members)) for r in recipes for members in r["ingredients"] if members})
    require(len(sets) <= 1024 and max(map(len, sets)) <= 2048 and sum(map(len, sets)) <= 131072, "ingredient resource census exceeded")
    set_index = {members: i for i, members in enumerate(sets)}
    lines = ["// Generated by tests/reference/generate_normal_crafting.py from actual original codec products.",
             "// Minecraft 1.21.8, protocol 772. Do not edit these descriptors by hand.",
             "use super::{RawOutput, RawRecipe};", "#[rustfmt::skip]", "pub(super) static INGREDIENTS: &[&[i32]] = &["]
    for members in sets:
        lines.append("    &[" + ", ".join(map(str, members)) + "],")
    lines.extend(["];", "#[rustfmt::skip]", "pub(super) static RECIPES: &[RawRecipe] = &["])
    patch_count = 0
    for recipe in recipes:
        result = recipe["result"]
        require(not result.get("empty") and 1 <= result["count"] <= 16, "invalid fixed output")
        require(len(result["added"]) + len(result["removed"]) <= 9, "result patch bound exceeded")
        if result["added"]:
            patch_count += 1
            require(len(result["added"]) == 1 and result["added"][0]["name"] == "minecraft:suspicious_stew_effects" and not result["removed"], "unexpected normal output component")
        additions = []
        for component in result["added"]:
            payload = bytes.fromhex(component["payload"])
            require(len(payload) <= 8192, "result payload exceeded")
            additions.append(f"({component['id']}, &[{', '.join(map(str, payload))}])")
        slots = [65535 if not members else set_index[tuple(sorted(item_ids[name] for name in members))] for members in recipe["ingredients"]]
        require(1 <= len(slots) <= 9, "recipe slot bound exceeded")
        if recipe["shaped"]:
            require(1 <= recipe["width"] <= 3 and 1 <= recipe["height"] <= 3 and len(slots) == recipe["width"] * recipe["height"], "invalid original pattern")
        lines.append("    RawRecipe { name: " + rust_string(recipe["name"]) +
                     f", shaped: {str(recipe['shaped']).lower()}, width: {recipe['width'] if recipe['shaped'] else 0}, height: {recipe['height'] if recipe['shaped'] else 0}, slots: &[{', '.join(map(str, slots))}], result: RawOutput {{ item: " +
                     rust_string(result["item"]) + f", count: {result['count']}, added: &[{', '.join(additions)}], removed: &[{', '.join(map(str, result['removed']))}] }} }},")
    require(patch_count == 16, "stew output census mismatch")
    lines.extend(["];", "#[rustfmt::skip]", "pub(super) static REMAINDERS: &[(&str, &str)] = &["])
    remainder_items = [r for r in items if not r.get("empty")]
    for item in remainder_items:
        require(item["count"] == 1 and not item["added"] and not item["removed"], "unexpected original remainder patch/count")
        lines.append("    (" + rust_string(item["source"]) + ", " + rust_string(item["item"]) + "),")
    lines.extend(["];", "#[rustfmt::skip]", "pub(super) static ITEM_PINS: &[(&str, i32, u8)] = &["])
    for item in items:
        lines.append("    (" + rust_string(item["source"]) + f", {item['id']}, {item['max']}),")
    lines.extend(["];", ""])
    rust = "\n".join(lines).encode()
    rows = ["# original Recipe.matches/assemble/CraftingRecipe.getRemainingItems and ItemStack.copyWithCount stream encodings"]
    identities = set()
    for case in cases:
        identity = (case["recipe"], case["side"], case["label"])
        require(identity not in identities, "duplicate differential case")
        identities.add(identity)
        slots = ["-" if s is None else f"{s[0]}:{s[1]}:{int(s[2])}" for s in case["input"]]
        require(case["side"] in (2, 3) and len(slots) == case["side"] ** 2, "invalid original case grid")
        fields = [case["recipe"], case["label"], str(case["side"]), ",".join(slots), str(int(case["matches"]))]
        fields.extend([case.get("output", "-"), ",".join(case.get("after", [])) or "-", ",".join(case.get("remainders", [])) or "-"])
        rows.append("\t".join(fields))
    tsv = ("\n".join(rows) + "\n").encode()
    require({r["name"] for r in recipes} == {r["recipe"] for r in cases if r["matches"]}, "normal actual-JAR matches incomplete")
    source_tags = set()
    def tags(value):
        if isinstance(value, str) and value.startswith("#"):
            source_tags.add(value[1:])
        elif isinstance(value, (list, tuple)):
            for child in value:
                tags(child)
        elif isinstance(value, dict):
            for child in value.values():
                tags(child)
    original = json.loads(fixture.read_bytes())["entries"]
    for recipe in recipes:
        tags(original[recipe["name"]].get("key", original[recipe["name"]].get("ingredients")))
    require(len(source_tags) == 25, "original normal tag census mismatch")
    return rust, tsv, {"recipes": len(recipes), "shaped": 673, "shapeless": 295, "ingredient_sets": len(sets), "largest_ingredient_set": max(map(len, sets)), "ingredient_memberships": sum(map(len, sets)), "original_item_registry": len(items), "remainder_items": len(remainder_items), "component_outputs": patch_count, "cases": len(cases), "tag_references": sorted(source_tags)}


def main():
    require(len(sys.argv) == 4, "expected ORIGINAL_CACHE JAVA_HOME OUTPUT_DIR")
    cache, java_home, output = (Path(v).resolve() for v in sys.argv[1:])
    output.mkdir(parents=True, exist_ok=True)
    source = Path(__file__).with_name("normal_crafting_oracle.java").resolve()
    fixture = Path(__file__).resolve().parents[5] / "docs/fixtures/minecraft-1.21.8-original/recipes.json"
    bundle, inner = cache / "server.jar", cache / "versions/1.21.8/server-1.21.8.jar"
    verify(bundle, PINS["bundle"], "official bundle"); verify(inner, PINS["inner"], "official inner JAR")
    verify(fixture, PINS["recipes"], "original recipes fixture")
    mappings = output / "server-mappings.txt"
    # Explicit local verified mappings; this producer needs no network or download.
    require(mappings.exists(), "copy the pinned official server-mappings.txt into OUTPUT_DIR first")
    verify(mappings, PINS["mappings"], "official mappings")
    classpath = [inner]; libraries = {}
    with zipfile.ZipFile(bundle) as archive:
        for line in archive.read("META-INF/libraries.list").decode().splitlines():
            digest, coordinate, relative = line.split("\t")
            path = cache / "libraries" / relative
            verify(path, digest, f"official library: {coordinate}")
            classpath.append(path); libraries[coordinate] = digest
    require(len(libraries) == 43 and len(classpath) == len(set(classpath)) == 44, "official classpath census mismatch")
    reject_shadow(classpath)
    for variable in ("JAVA_TOOL_OPTIONS", "_JAVA_OPTIONS", "JDK_JAVA_OPTIONS"):
        require(not os.environ.get(variable), f"unsupported Java classpath/agent injection: {variable}")
    java, javac = java_home / "bin/java", java_home / "bin/javac"
    version = subprocess.run([str(java), "-version"], capture_output=True, text=True, check=True).stderr
    require(re.search(r'\bversion "21(?:\.|\")', version) is not None, "oracle requires Java 21")
    artifacts = [bundle, inner, mappings, fixture, source, Path(__file__).resolve(), *classpath[1:], java, javac]
    before = {p: sha256(p) for p in artifacts}
    cp = os.pathsep.join(str(p.resolve()) for p in classpath)
    raw = output / "normal_crafting_1_21_8.jsonl"
    with tempfile.TemporaryDirectory(prefix="crafting-oracle-classes-", dir=output) as classes:
        subprocess.run([str(javac), "-proc:none", "-encoding", "UTF-8", "-cp", cp, "-d", classes, str(source)], check=True)
        subprocess.run([str(java), "-Xmx512m", "-cp", cp + os.pathsep + classes, "ferrumc.reference.NormalCraftingOracle", str(fixture), str(raw), str(inner), classes], cwd=output, check=True)
    require(before == {p: sha256(p) for p in artifacts}, "oracle input changed during execution")
    reject_shadow(classpath)
    require(raw.stat().st_size <= MAX_EXPORT, "original export size exceeded")
    records = [json.loads(line) for line in raw.read_text().splitlines()]
    rust, tsv, census = producer(records, fixture)
    (output / "normal_recipes_generated.rs").write_bytes(rust)
    cases = output / "normal_crafting_1_21_8.tsv"; cases.write_bytes(tsv)
    manifest = {"minecraft": "1.21.8", "protocol": 772, "data_version": 4440, "pins": PINS, "libraries_sha256": libraries, "java": version.strip(), "javac": subprocess.run([str(javac), "-version"], capture_output=True, text=True, check=True).stdout.strip(), "python": platform.python_version(), "oracle_sha256": sha256(source), "generator_sha256": sha256(Path(__file__)), "census": census, "raw_bytes": raw.stat().st_size, "raw_sha256": sha256(raw), "cases_bytes": len(tsv), "cases_sha256": sha256(cases), "descriptors_bytes": len(rust), "descriptors_sha256": hashlib.sha256(rust).hexdigest(), "origin_validation": "30 original class CodeSources, fresh helper CodeSource, classpath shadow rejection", "inputs_rehashed": len(before), "source": "actual Original-JAR tag loader with PendingTags.apply, Recipe.CODEC, Ingredient.items, matches/assemble, CraftingRecipe.getRemainingItems, Item.getCraftingRemainder and original stream codecs"}
    (output / "normal_crafting_1_21_8.manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    print(json.dumps(census, sort_keys=True))


if __name__ == "__main__":
    main()
