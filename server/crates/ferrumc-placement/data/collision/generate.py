#!/usr/bin/env python3
"""Freeze original placement shapes and geometric probes after exact registry checks."""
import csv
import hashlib
import json
from pathlib import Path
import struct
import sys


def require(condition, label):
    if not condition:
        raise ValueError(label)


root = Path(__file__).resolve().parents[5]
source = Path(sys.argv[1]).resolve()
probe_source = source.with_name('probes.tsv')
output = Path(__file__).resolve().parent
rows = list(csv.DictReader(source.open(), delimiter='\t'))
blocks_path = root / 'server/crates/ferrumc-registry/data/blocks.json'
blocks = json.loads(blocks_path.read_text())
by_id = {}
for block in blocks:
    for state_id in range(block['minStateId'], block['maxStateId'] + 1):
        value = state_id - block['minStateId']
        props = {}
        for prop in reversed(block['states']):
            values = ['true', 'false'] if prop['type'] == 'bool' else prop.get('values', [str(i) for i in range(prop['num_values'])])
            props[prop['name']] = values[value % len(values)]
            value //= len(values)
        require(value == 0, 'complete state radix')
        by_id[state_id] = (block['name'], props)
require(len(rows) == len(by_id) and len(rows) == 27946, 'complete pinned original state membership')
shapes, shape_ids, index, excluded = [], {}, [], set()
for expected_id, row in enumerate(rows):
    state_id = int(row['id'])
    require(state_id == expected_id, 'dense original ids')
    actual_props = dict(pair.split('=', 1) for pair in row['properties'][1:-1].split(', ') if pair)
    name, props = by_id[state_id]
    require(row['block'] == 'minecraft:' + name and props == actual_props, f'original exact state identity {state_id}')
    boxes = tuple(tuple(float(n) for n in box.split(',')) for box in row['placement_boxes'].split(';') if box)
    for box in boxes:
        require(len(box) == 6 and all(box[i] < box[i + 3] for i in range(3)), 'nonempty original box')
    supported_dynamic = row['class'] in {
        'net.minecraft.world.level.block.ShulkerBoxBlock',  # Fresh placement has no opening block entity.
        'net.minecraft.world.level.block.ScaffoldingBlock',
        'net.minecraft.world.level.block.PowderSnowBlock',
    }
    if (boxes and row['offset'] == 'true') or (row['dynamic'] == 'true' and not supported_dynamic):
        index.append(65535)
        excluded.add(row['block'])
        continue
    require(row['placement_boxes'] == row['shifted_boxes'], 'supported position-independent shape')
    if boxes not in shape_ids:
        shape_ids[boxes] = len(shapes)
        shapes.append(boxes)
    index.append(shape_ids[boxes])
require(len(shapes) < 65535, 'bounded shape index')
(output / 'state-shapes.bin').write_bytes(b''.join(struct.pack('<H', item) for item in index))
lines = ['// Generated by data/collision/generate.py from the pinned original runtime.', '// Do not edit this shape table by hand.', 'pub(super) const SHAPES: &[&[[f64; 6]]] = &[']
for boxes in shapes:
    lines.append('    &[' + ', '.join('[' + ', '.join(repr(n) for n in box) + ']' for box in boxes) + '],')
lines.append('];')
(root / 'server/crates/ferrumc-placement/src/collision_data.rs').write_text('\n'.join(lines) + '\n')
probes = list(csv.DictReader(probe_source.open(), delimiter='\t'))
require(len(probes) == len(rows) * 16, 'complete genuine geometry probes')
controls = []
for case in range(16):
    r = probes[case]
    controls.append({'position': [int(r[axis]) for axis in ['px', 'py', 'pz']], 'feet': [float(r[axis]) for axis in ['x', 'y', 'z']]})
golden = bytearray()
for i, row in enumerate(probes):
    require(int(row['id']) == i // 16 and int(row['case']) == i % 16, 'ordered genuine probe')
    require([float(row[a]) for a in ['x', 'y', 'z']] == controls[i % 16]['feet'], 'identical body controls')
    require([int(row[a]) for a in ['px', 'py', 'pz']] == controls[i % 16]['position'], 'identical block origins')
    require(row['intersects'] in ['true', 'false'], 'genuine bool result')
    golden.append(int(row['intersects'] == 'true'))
(output / 'probe-results.bin').write_bytes(golden)
(output / 'probe-feet.json').write_text(json.dumps(controls, indent=2) + '\n')
hash_file = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
manifest = {
    'minecraft': '1.21.8', 'protocol': 772, 'paper_build': 60,
    'paper_commit': '29c8822d90899c89d2689338e81a98f690bcba12',
    'paper_inner_sha256': 'c64fb7dbc95cd15aa0b7460a5b1e117eef5ee91c4e6fa7a8f1fe6487b6c31507',
    'original_shapes_sha256': hash_file(source), 'original_probes_sha256': hash_file(probe_source),
    'registry_blocks_sha256': hash_file(blocks_path), 'oracle_source_sha256': hash_file(output / 'CollisionShapeOracle.java'),
    'states': len(rows), 'distinct_supported_shapes': len(shapes), 'supported_states': sum(s != 65535 for s in index),
    'excluded_blocks': sorted(excluded), 'genuine_probe_cases': len(probes),
    'body_dimensions': 'original EntityDimensions.scalable(0.6F,1.8F).makeBoundingBox; feet controls in probe-feet.json',
    'shape_context': 'actual CollisionContext.placementContext(null), EmptyBlockGetter; fresh placement only',
    'scope': 'static placement shapes and fresh closed shulkers; colliding offset and moving-piston states refuse; standing players only; no full entity/canSee/world support parity',
}
(output / 'provenance.json').write_text(json.dumps(manifest, indent=2) + '\n')
print(json.dumps(manifest, indent=2))
